// Writes ../src/kiswah.js from verses.json (Quran text fetched from quran.ai, edition ar-uthmani-hafs) and the
// Noto Naskh Arabic Bold subset (OFL-1.1, see OFL-NotoNaskhArabic.txt). The verse strings are copied byte for
// byte, never retyped. Re-run after changing either input:
//   node text/make-kiswah.mjs            (from source/)
// To rebuild the font subset (fonttools):
//   pyftsubset /usr/share/fonts/noto/NotoNaskhArabic-Bold.ttf --text-file=text/chars.txt --layout-features='*' \
//     --flavor=woff --output-file=text/naskh-subset.woff
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const v = JSON.parse(readFileSync(path.join(here, 'verses.json'), 'utf8'));
const order = ['+x', '+z', '-x', '-z'];
const belt = order.map((s) => v.belt.find((b) => b.side === s));
const font = readFileSync(path.join(here, 'naskh-subset.woff')).toString('base64');
const out = `// ============================================================================
// the Kiswah's belt text: verified Quran verses, drawn once into a texture (generated by text/make-kiswah.mjs)
// ============================================================================
// Text: ${v.source}. Belt order +x, +z, -x, -z: ${belt.map((b) => b.ref).join(', ')}.
// Font: Noto Naskh Arabic Bold, subset to these verses, SIL Open Font License 1.1 (text/OFL-NotoNaskhArabic.txt).
const KISWAH_BELT = ${JSON.stringify(belt.map((b) => b.text))};
const KISWAH_FONT = '${font}';
`;
writeFileSync(path.join(here, '..', 'src', 'kiswah.js'), out);
console.log('src/kiswah.js', out.length, 'bytes');
